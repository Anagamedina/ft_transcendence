# SERVICE — alerts
# Business rules and orchestration. No HTTP here.
# AlertService: rules, acknowledge, resolve (transactions).
"""
Alert logic.

Alerts are generated by the backend, never by the client: the document is
explicit that the simulator only measures and that anomaly detection is
business logic (section 1.3). That is why there is no public `create`
here — creation happens as a side effect of storing a reading, from
`ReadingService`.

The three MVP rules (section 1.2):

    pressure < sensor min_pressure   → LOW_PRESSURE
    pressure > sensor max_pressure   → HIGH_PRESSURE
    last_seen_at too old             → SENSOR_OFFLINE

The first two are evaluated when a reading arrives (`alerts/rules.py`).
The third is not: it fires on the **absence** of data, so a background
task checks it every minute (`alerts/offline.py`, started from
`main.py`). The same task closes alerts once the readings have been
normal for 15 minutes (`alerts/autoclose.py`, #277).

Implementation: issue #28 (PRs #78, #98 and #118).
"""

from __future__ import annotations

from datetime import datetime, timezone

from uuid import UUID

from sqlalchemy.orm import Session

from app.core.database import transaction
from app.core.exceptions import ConflictError, DomainValidationError, NotFoundError
from app.modules.alerts.autoclose import normal_desde, se_cierra_a
from app.modules.alerts.notices import siguiente_aviso
from app.modules.alerts.repository import AlertRepository
from app.modules.alerts.schemas import AlertNotificationResponse, AlertResponse, AlertState
from app.shared.dependencies import DbSession, _as_utc
from app.shared.schemas import Page


class AlertService:
    def __init__(self, db: Session, alerts: AlertRepository | None = None) -> None:
        self.db = db
        self.alerts = alerts or AlertRepository(db)

    def list(
        self,
        organization_id: UUID | None,
        offset: int,
        limit: int,
        status: str | None = None,
        sensor_id: UUID | None = None,
        q: str | None = None,
        organization_filter: UUID | None = None,
        site_id: UUID | None = None,
        severity: str | None = None,
        state: str | None = None,
        created_from: datetime | None = None,
        created_to: datetime | None = None,
    ) -> Page[AlertResponse]:
        """
        Alerts of the organization, paginated.

        `status` keeps the stored life cycle; `state` tells active
        unacknowledged alerts from acknowledged ones. Severity and dates
        are combined with the common filters before counting and
        paginating.

        `organization_id` always comes from `get_org_scope`: without it,
        anyone would see another client's alerts. `None` means "all
        organizations", and is only given to an admin (issue #27).

        `q` searches the message, the sensor name and code, the building
        and the client (#252); `organization_filter` and `site_id` are the
        common filters of B0.
        """
        created_from = _as_utc(created_from) if created_from is not None else None
        created_to = _as_utc(created_to) if created_to is not None else None
        if created_from is not None and created_to is not None and created_from >= created_to:
            raise DomainValidationError(
                "`created_from` tiene que ser anterior a `created_to`.",
                code="INVALID_DATE_RANGE",
                details={"field": "created_from", "message": "Debe ser anterior a `created_to`."},
            )
        filas, total = self.alerts.list_by_organization(
            organization_id=organization_id,
            status=status,
            sensor_id=sensor_id,
            offset=offset,
            limit=limit,
            q=q,
            organization_filter=organization_filter,
            site_id=site_id,
            severity=severity,
            state=state,
            created_from=created_from,
            created_to=created_to,
        )
        return Page[AlertResponse](
            items=[self._to_response(f) for f in filas],
            total=total,
            page=offset // limit + 1,
            page_size=limit,
        )

    def acknowledge(
        self, alert_id: UUID, organization_id: UUID | None, actor_id: UUID,
    ) -> AlertResponse:
        """
        Marks the alert as acknowledged: someone has seen it.

        It is idempotent. If two operators press at the same time, the
        second call neither fails nor overwrites the first one's
        timestamp: what matters is when it was acknowledged for the FIRST
        time, not the last time someone clicked. The repository gives that
        guarantee, writing only if the field was empty.

        Acknowledging is not resolving: the alert stays active, it only
        records that someone is aware.
        """
        with transaction(self.db):
            alerta = self._propia_o_404(alert_id, organization_id)
            self.alerts.acknowledge(alerta.id, datetime.now(timezone.utc), actor_id)

        return self._to_response(alerta)

    def resolve(
        self, alert_id: UUID, organization_id: UUID | None, actor_id: UUID,
    ) -> AlertResponse:
        """
        Closes the alert.

        Resolving one already resolved is a `ConflictError`, not a silent
        success: it would overwrite `resolved_at` and lose when it was
        really handled. And that date is what measures how long the
        response took.

        The check is done with the row locked to keep the first resolution
        even with two simultaneous requests.
        """
        with transaction(self.db):
            alerta = self._propia_o_404(alert_id, organization_id)
            if alerta.status == "RESOLVED":
                raise ConflictError(
                    "Esa alerta ya estaba resuelta.",
                    code="ALERT_ALREADY_RESOLVED",
                )
            self.alerts.resolve(alerta.id, datetime.now(timezone.utc), actor_id)

        return self._to_response(alerta)

    def _propia_o_404(self, alert_id: UUID, organization_id: UUID | None):
        """
        The alert, only if it belongs to that organization.

        It is checked here because the repository `acknowledge` and
        `resolve` look up by id alone, without filtering. Without this
        step, anyone guessing the id of someone else's alert could mark it
        as seen or close it.

        An alert from another organization answers the same as one that
        does not exist: saying "it exists but it is not yours" already
        confirms that id is real.
        """
        alerta = self.alerts.get_by_id(alert_id, organization_id, for_update=True)
        if alerta is None:
            raise NotFoundError(
                "La alerta indicada no existe.",
                code="ALERT_NOT_FOUND",
            )
        return alerta

    def _to_response(self, alerta) -> AlertResponse:
        """
        Converts the row to the output schema.

        A direct `model_validate` does not work: the contract calls `type`
        what the table stores as `alert_type`. It is the same vocabulary
        mismatch already translated in readings, and it is solved where it
        belongs — in the service, which knows both sides.

        The read-only fields (B0) go up `alert → sensor → site →
        organization`. In lists the repository already loads them in bulk
        (`selectinload`), so no query per alert is made here. `state` is
        computed with `AlertState.derive`.
        """
        sensor = alerta.sensor
        site = sensor.site
        # #277: if the readings are already normal, the closing is being confirmed
        normal = normal_desde(self.db, alerta)
        return AlertResponse(
            id=alerta.id,
            sensor_id=alerta.sensor_id,
            sensor_name=sensor.name,
            site_id=site.id,
            site_name=site.name,
            organization_id=site.organization_id,
            organization_name=site.organization.name,
            floor=sensor.floor,
            type=alerta.alert_type,
            severity=alerta.severity,
            message=alerta.message,
            threshold=_limite(alerta.alert_type, sensor),
            status=alerta.status,
            state=AlertState.derive(alerta.status, alerta.acknowledged_at),
            created_at=_as_utc(alerta.created_at),
            acknowledged_at=_as_utc(alerta.acknowledged_at) if alerta.acknowledged_at else None,
            resolved_at=_as_utc(alerta.resolved_at) if alerta.resolved_at else None,
            acknowledged_by_name=(
                alerta.acknowledged_by_user.name if alerta.acknowledged_by_user else None
            ),
            resolved_by_name=(
                alerta.resolved_by_user.name if alerta.resolved_by_user else None
            ),
            notifications=[
                AlertNotificationResponse(
                    attempt=n.attempt,
                    channel=n.channel,
                    recipient=n.recipient,
                    sent_at=_as_utc(n.sent_at),
                )
                for n in alerta.notifications
            ],
            next_notification_at=None if normal else siguiente_aviso(alerta),
            normal_since=normal,
            closes_at=se_cierra_a(normal),
            resolution_minutes=(
                (_as_utc(alerta.resolved_at) - _as_utc(alerta.created_at)).total_seconds() / 60
                if alerta.status == "RESOLVED" and alerta.resolved_at is not None else None
            ),
        )


def _limite(alert_type: str, sensor) -> float | None:
    """The threshold of the alert (to show "1,1 bar · mín. 1,5")."""
    valor = {
        "LOW_PRESSURE": sensor.low_threshold,
        "HIGH_PRESSURE": sensor.high_threshold,
    }.get(alert_type)
    return float(valor) if valor is not None else None


def get_alert_service(db: DbSession) -> AlertService:
    """Service provider for `Depends`."""
    return AlertService(db)
