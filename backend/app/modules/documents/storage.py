# STORAGE — documents
# Files of the documents on disk, under DOCUMENTS_DIR (B11).
"""
The `documents` table only holds metadata; the bytes live on disk, in
`DOCUMENTS_DIR / storage_key`. This module is the only place that touches
those files.

For now it only deletes them (B16, deleting an organization). Uploading
and downloading arrive with B11 and belong here too.
"""

from __future__ import annotations

import logging
from collections.abc import Iterable
from pathlib import Path

from app.core.app_config import app_settings

logger = logging.getLogger(__name__)


def _path(storage_key: str, root: Path) -> Path | None:
    """
    The file of a storage_key, or None if the key points outside the
    documents folder. storage_key is generated by the backend, never the
    user, but a stray `../` must never delete anything else.
    """
    path = (root / storage_key).resolve()
    if not path.is_relative_to(root):
        return None
    return path


def delete_files(storage_keys: Iterable[str], root: str | Path | None = None) -> int:
    """
    Deletes the files of these documents and returns how many were deleted.

    Call it after the commit: if the transaction fails, the files must still
    be there. A missing file is not an error (it may never have been
    uploaded), and a file that cannot be deleted is logged, not raised: the
    rows are already gone and the request must not fail because of it.
    """
    base = Path(root or app_settings.DOCUMENTS_DIR).resolve()
    deleted = 0
    for key in storage_keys:
        path = _path(key, base)
        if path is None:
            logger.warning("storage_key outside DOCUMENTS_DIR, not deleted: %s", key)
            continue
        try:
            path.unlink()
            deleted += 1
        except FileNotFoundError:
            continue
        except OSError:
            logger.exception("Could not delete document file %s", path)
    return deleted
